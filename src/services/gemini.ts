export async function generateHtmlApp(topic: string, requirements?: string): Promise<GeneratedHtmlApp> {
  const prompt = `Create a single-file, production-ready, beautiful and interactive HTML/CSS/JavaScript web application or tool for: "${topic}".
User requirements: ${requirements || 'Make it fully functional, modern, responsive, styled with embedded CSS or CDN Tailwind, with interactive buttons, state, and slick animations.'}

CRITICAL RULES:
1. Return ONLY the complete standalone HTML code enclosed in a \`\`\`html codeblock.
2. Must contain <!DOCTYPE html>, <html>, <head>, <style>, <body>, and <script> tags.
3. Use Tailwind CSS via <script src="https://cdn.tailwindcss.com"></script> and FontAwesome or modern SVG icons.
4. It must work 100% locally in an iframe with working interactive features (e.g. functional calculator, todo list, timer, game, dashboard, form validator, or generator).
5. Never return incomplete code or placeholders. Include all UI and logic.`;

  const response = await callGeminiApi(prompt, 'You are an elite Senior Frontend Architect & AI System Engineer.');
  
  const match = response.match(/```html([\s\S]*?)```/);
  const code = match ? match[1].trim() : response.trim();

  return {
    title: topic,
    description: `Generated interactive web application for: ${topic}`,
    code,
    timestamp: new Date().toLocaleTimeString()
  };
}

