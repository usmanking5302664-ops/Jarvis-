export function setCustomApiKey(key: string) {
  if (key.trim()) {
    localStorage.setItem('CUSTOM_GEMINI_API_KEY', key.trim());
  } else {
    localStorage.removeItem('CUSTOM_GEMINI_API_KEY');
  }
}

async function callGeminiApi(prompt: string, systemInstruction?: string, model: string = PRIMARY_MODEL): Promise<string> {
  const effectiveKey = getEffectiveApiKey();
  if (!effectiveKey) {
    throw new Error('Gemini API Key is missing. Please configure GEMINI_API_KEY in Secrets or enter it in settings.');
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${effectiveKey}`;
  
  const body: any = {
    contents: [
      {
        parts: [{ text: prompt }]
      }
    ],
    generationConfig: {
      temperature: 0.7,
      topP: 0.95,
      maxOutputTokens: 8192
    }
  };

  if (systemInstruction) {
    body.systemInstruction = {
      parts: [{ text: systemInstruction }]
    };
  }

  try {
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body)
    });

    if (!res.ok) {
      const errText = await res.text();
      // Try fallback model if 404 or preview not available
      if (model === PRIMARY_MODEL && (res.status === 404 || res.status === 400)) {
        return callGeminiApi(prompt, systemInstruction, FALLBACK_MODEL);
      }
      throw new Error(`Gemini API error (${res.status}): ${errText}`);
    }

    const data = await res.json();
    const candidateText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidateText) {
      throw new Error('No response text generated by Gemini');
    }
    return candidateText;
  } catch (error: any) {
    if (model === PRIMARY_MODEL) {
      console.warn(`Primary model ${PRIMARY_MODEL} failed, attempting fallback to ${FALLBACK_MODEL}`, error);
      return callGeminiApi(prompt, systemInstruction, FALLBACK_MODEL);
    }
    throw error;
  }
}

